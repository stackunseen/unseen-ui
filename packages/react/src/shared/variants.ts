export type VariantComponent = keyof typeof componentVariants;
export type ComponentVariant<K extends VariantComponent> = (typeof componentVariants)[K][number];
export type VariantProps<K extends VariantComponent> = { variant?: ComponentVariant<K> };
/** Useful for validated controls and docs. Unknown input returns the default presentation. */
export function resolveVariant<K extends VariantComponent>(
  name: K,
  value?: string,
): ComponentVariant<K> {
  const options: readonly string[] = componentVariants[name];
  return (value && options.includes(value) ? value : options[0]) as ComponentVariant<K>;
}
