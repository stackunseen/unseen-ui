// Writes lib/pattern-usage.ts: which catalog components each pattern imports from the library.
// Run after changing a pattern: node apps/docs/scripts/generate-pattern-usage.mjs
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import console from 'node:console';

const docs = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const patterns = [
  [
    'AI SDK chat',
    '/patterns/ai-sdk-chat/',
    ['components/ai-recipes/ai-sdk-chat-recipe.tsx', 'components/chat-ai-sdk-specimen.tsx'],
  ],
  ['Recoverable chat', '/patterns/recoverable-chat/', ['components/ai-recipes/recovery']],
  ['Action receipts', '/patterns/action-receipts/', ['components/ai-recipes/actions']],
  ['Research answers', '/patterns/research-answers/', ['components/ai-recipes/research']],
  [
    'Workspace integrations',
    '/patterns/workspace-integrations/',
    ['components/workspace-upgrades'],
  ],
  [
    'Agent Workbench',
    '/patterns/agent-workbench/',
    ['components/workbench.tsx', 'components/workbench-panels.tsx'],
  ],
  [
    'Coding Studio',
    '/patterns/coding-studio/',
    ['components/coding-studio.tsx', 'components/coding-studio'],
  ],
  ['SaaS admin', '/templates/saas-admin/', ['components/saas-admin']],
  ['Marketing', '/templates/marketing/', ['components/marketing-template']],
];

function files(path) {
  const full = join(docs, path);
  let stat;
  try {
    stat = statSync(full);
  } catch {
    return [];
  }
  if (stat.isFile()) return /\.tsx?$/.test(full) && !/\.test\./.test(full) ? [full] : [];
  return readdirSync(full).flatMap((name) => files(join(path, name)));
}

const usage = {};
for (const [label, href, paths] of patterns) {
  const names = new Set();
  for (const file of paths.flatMap(files)) {
    const source = readFileSync(file, 'utf8');
    for (const match of source.matchAll(
      /import\s*(?:type\s*)?\{([^}]*)\}\s*from\s*'@stackunseen\/ui[^']*'/g,
    )) {
      if (/^\s*import\s+type/.test(match[0])) continue;
      for (const raw of match[1].split(',')) {
        const name = raw
          .trim()
          .replace(/^type\s+/, '')
          .split(/\s+as\s+/)[0];
        if (/^[A-Z][A-Za-z]+$/.test(name)) names.add(name);
      }
    }
  }
  for (const name of names) (usage[name] ??= []).push({ label, href });
}
const body = Object.keys(usage)
  .sort()
  .map((name) => `  ${name}: ${JSON.stringify(usage[name])},`)
  .join('\n');
writeFileSync(
  join(docs, 'lib/pattern-usage.ts'),
  `// Generated by scripts/generate-pattern-usage.mjs from each pattern's library imports.\nexport interface PatternLink {\n  label: string;\n  href: string;\n}\nexport const patternUsage: Record<string, readonly PatternLink[]> = {\n${body}\n};\n\nexport function patternsUsing(name: string): readonly PatternLink[] {\n  return patternUsage[name] ?? [];\n}\n`,
);
console.log(`${Object.keys(usage).length} components used across ${patterns.length} patterns`);
